module.exports.prepare=async({js,click,invoke,waitFor,root})=>{
  const {normalizePhoto,preparePhoto}=require(path.join(process.env.BOSS_SHOP_TEST_APP_ROOT||path.join(__dirname,'..'),'electron/product-photo.cjs'))
  const source=fs.readFileSync(path.join(root,'photo.jpg'))
  const image=nativeImage.createFromBuffer(source)
  assert.equal(image.isEmpty(),false)
  for(const data of [source,image.toPNG()])assert.ok(normalizePhoto(data,nativeImage).startsWith('data:image/jpeg;base64,'))
  const webp=await js(`(()=>{const c=document.createElement('canvas');c.width=40;c.height=30;c.getContext('2d').fillRect(0,0,40,30);return c.toDataURL('image/webp')})()`)
  assert.ok(webp.startsWith('data:image/webp;'));assert.ok(await preparePhoto(Buffer.from(webp.split(',')[1],'base64'),require('electron')))
  const huge=image.toPNG();huge.writeUInt32BE(12001,16)
  for(const data of [Buffer.alloc(10*1024*1024+1),Buffer.from('<svg></svg>'),source.subarray(0,30),huge])assert.throws(()=>normalizePhoto(data,nativeImage))
  const large=nativeImage.createFromBuffer(Buffer.from(await js(`(()=>{const c=document.createElement('canvas');c.width=1800;c.height=1400;c.getContext('2d').fillRect(0,0,1800,1400);return c.toDataURL('image/png').split(',')[1]})()`),'base64'))
  const reduced=normalizePhoto(large.toPNG(),nativeImage)
  assert.equal(nativeImage.createFromBuffer(Buffer.from(reduced.split(',')[1],'base64')).getSize().width,1200)
  await click('Добавить товар');await waitFor(()=>js('Boolean(document.querySelector(".photo-editor"))'))
  const picker=dialog.showOpenDialog
  dialog.showOpenDialog=async()=>({canceled:true,filePaths:[]})
  try {
    await click('Добавить фото');await waitFor(()=>js('Array.from(document.querySelectorAll(".photo-editor button")).some(x=>x.innerText==="Добавить фото"&&!x.disabled)'))
    assert.equal(await js('Boolean(document.querySelector(".photo-editor img"))'),false)
  } finally {dialog.showOpenDialog=picker}
  fs.writeFileSync(path.join(root,'photo.jpg'),'invalid image')
  await click('Добавить фото');await waitFor(()=>js('Boolean(document.querySelector(".form-error"))'))
  fs.writeFileSync(path.join(root,'photo.jpg'),source)
  await click('Добавить фото');await waitFor(()=>js('Boolean(document.querySelector(".photo-editor img")?.naturalWidth)'))
  await click('Отмена',`document.querySelector('.modal')`)
  assert.deepEqual((await invoke('listProducts')).data,[],'Canceled new model wrote to database')
}
