const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')

module.exports=async({js,invoke,waitFor,win,root,log})=>{
  const run=code=>js(`(()=>{${code}})()`)
  const click=async(text,scope='document')=>{
    await run(`const button=Array.from(${scope}.querySelectorAll('button')).find(x=>x.textContent.trim()===${JSON.stringify(text)});if(!button)throw new Error('Missing button: '+${JSON.stringify(text)});button.click()`)
  }
  const fill=async(selector,value)=>{
    await run(`const node=document.querySelector(${JSON.stringify(selector)});if(!node)throw new Error('Missing input: '+${JSON.stringify(selector)});const proto=node.tagName==='SELECT'?HTMLSelectElement.prototype:node.tagName==='TEXTAREA'?HTMLTextAreaElement.prototype:HTMLInputElement.prototype;Object.getOwnPropertyDescriptor(proto,'value').set.call(node,${JSON.stringify(String(value))});node.dispatchEvent(new Event(node.tagName==='SELECT'?'change':'input',{bubbles:true}))`)
    await waitFor(()=>js(`document.querySelector(${JSON.stringify(selector)})?.value===${JSON.stringify(String(value))}`))
  }
  const fillLabel=async(label,value)=>{
    await run(`const label=Array.from(document.querySelectorAll('.modal .field')).find(x=>x.querySelector('.field-label')?.textContent===${JSON.stringify(label)});if(!label)throw new Error('Missing field '+${JSON.stringify(label)});label.querySelector('input,select,textarea').setAttribute('data-feature-field','current')`)
    await fill('[data-feature-field="current"]',value)
    await run(`document.querySelector('[data-feature-field="current"]').removeAttribute('data-feature-field')`)
  }
  const nav=async text=>{await run(`Array.from(document.querySelectorAll('nav button')).find(x=>x.textContent.includes(${JSON.stringify(text)})).click()`)}
  const cat=(await invoke('bootstrap',{})).data.categories[0]
  await nav('Товары и остатки')
  await waitFor(()=>js('Boolean(document.querySelector(".products-page"))'))
  await require('./electron-catalog-ui.cjs').prepare({js,click,invoke,waitFor,root})
  await click('Добавить товар')
  await waitFor(()=>js('Boolean(document.querySelector(".modal .multi-size-editor"))'))
  assert.equal(await js('document.querySelector(".modal input").readOnly'),true)
  assert.ok((await js('document.querySelector(".modal input").value')).includes('присвоен'))
  await click('Добавить фото')
  await waitFor(()=>js('Boolean(document.querySelector(".photo-editor img")?.naturalWidth)'))
  await fillLabel('Название *','UI модель')
  await fillLabel('Категория',cat.id)
  await fillLabel('Бренд','UI Brand')
  await fillLabel('Закупочная цена, ₽','1.01')
  await fillLabel('Розничная цена, ₽','5')
  await fillLabel('Начальный остаток, шт.','4')
  await fill('[aria-label="Список размеров"]','XL, 48, M, 48, , НовыйUI')
  await click('Распределить размеры')
  await waitFor(()=>js('document.querySelectorAll(".multi-size-table tbody tr").length===4'))
  assert.deepEqual(await js('Array.from(document.querySelectorAll(".multi-size-table input[aria-label^=sizeName]")).map(x=>x.value)'),['XL','48','M','НовыйUI'])
  await fill('[aria-label="quantity 2"]','7')
  await fill('[aria-label="color 2"]','Синий')
  await click('Создать товар')
  await waitFor(()=>js('!document.querySelector(".modal")&&document.body.innerText.includes("UI модель")'))
  let products=(await invoke('listProducts',{search:'UI модель'})).data
  assert.equal(products.length,4);assert.equal(new Set(products.map(x=>x.productId)).size,1)
  assert.equal(products.find(x=>x.size==='48').quantity,7)
  assert.equal(products.find(x=>x.size==='48').color,'Синий')
  assert.equal(products.every(x=>x.brand==='UI Brand'&&x.categoryId===cat.id),true)
  const headers=await js('Array.from(document.querySelectorAll(".products-table-scroll thead th")).map(x=>x.textContent.trim())')
  assert.ok(headers.includes('Категория'));assert.ok(headers.includes('Бренд'));assert.ok(!headers.includes('Категория / бренд'))
  await run(`document.querySelector('button[aria-label="Изменить: Бренд"]').click()`)
  await waitFor(()=>js('Boolean(document.querySelector(".quick-editor input"))'))
  await fill('.quick-editor input','Independent Brand')
  await run(`document.querySelector('.quick-editor button[type=submit]').click()`)
  await waitFor(()=>js('document.body.innerText.includes("Independent Brand")&&!document.querySelector(".quick-editor")'))
  products=(await invoke('listProducts',{search:'UI модель'})).data
  assert.equal(products.every(x=>x.categoryId===cat.id&&x.brand==='Independent Brand'),true)
  // A second model proves that inner sorting never moves rows across models.
  const otherResult=await invoke('saveProduct',{product:{article:'UI-OTHER',name:'UI другая',purchasePrice:100,retailPrice:1000,initialQty:2}});assert.equal(otherResult.ok,true);const otherArticle=otherResult.data.article
  await nav('Продажи');await nav('Товары и остатки')
  await waitFor(()=>js('document.querySelectorAll(".product-group").length===2'))
  const order=await js('Array.from(document.querySelectorAll(".product-group")).map(x=>x.innerText)')
  await run(`Array.from(document.querySelectorAll('.product-expander')).forEach(x=>x.click())`)
  await waitFor(()=>js('document.querySelectorAll(".product-variant-row").length===5'))
  const getModelOrder=()=>js(`(()=>{const rows=Array.from(document.querySelectorAll('.products-table-scroll tbody tr'));let found=false,result=[];for(const row of rows){if(row.classList.contains('product-group'))found=row.innerText.includes('UI модель');else if(found&&row.classList.contains('product-variant-row'))result.push(Number(row.dataset.variantId))}return result})()`)
  const sizeOrder=await getModelOrder()
  assert.equal(sizeOrder[0],products.find(x=>x.size==='48').variantId)
  const sortedQuantity=products.slice().sort((a,b)=>a.quantity-b.quantity||a.variantId-b.variantId).map(x=>x.variantId)
  await run(`Array.from(document.querySelectorAll('.variant-sort-row button')).find(x=>x.textContent.includes('Остаток')).click()`)
  await waitFor(async()=>JSON.stringify(await getModelOrder())===JSON.stringify(sortedQuantity))
  await run(`Array.from(document.querySelectorAll('.variant-sort-row button')).find(x=>x.textContent.includes('Остаток')).click()`)
  await waitFor(async()=>JSON.stringify(await getModelOrder())===JSON.stringify(products.slice().sort((a,b)=>b.quantity-a.quantity||a.variantId-b.variantId).map(x=>x.variantId)))
  assert.deepEqual(await js('Array.from(document.querySelectorAll(".product-group")).map(x=>x.innerText)'),order)
  const shots=path.join(__dirname,'..','build','verification-1.3.4');fs.mkdirSync(shots,{recursive:true})
  await js('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))')
  fs.writeFileSync(path.join(shots,'products.png'),(await win.webContents.capturePage()).toPNG())
  const day=new Date(),calendar=[day.getFullYear(),String(day.getMonth()+1).padStart(2,'0'),String(day.getDate()).padStart(2,'0')].join('-')
  await nav('Продажи');await waitFor(()=>js('document.querySelector("h1")?.innerText==="Продажи"'))
  await click('Новая продажа')
  await waitFor(()=>js('Boolean(document.querySelector(".modal .cart-title"))'))
  assert.equal(await js('document.querySelector(".modal input").type'),'date')
  assert.equal(await js('Boolean(document.querySelector(".modal input[type=datetime-local]"))'),false)
  await fillLabel('Дата продажи',calendar)
  await fillLabel('Комментарий','UI created')
  await click('Добавить товар',`document.querySelector('.modal')`)
  await waitFor(()=>js('Boolean(document.querySelector(".picker-list button"))'))
  await run(`Array.from(document.querySelectorAll('.picker-list button')).find(x=>x.innerText.includes('UI модель')&&x.innerText.includes('48')).click()`)
  await waitFor(()=>js('document.querySelectorAll(".modal").length===1&&Boolean(document.querySelector(".cart-row"))'))
  await click('Провести продажу')
  await waitFor(()=>js('!document.querySelector(".modal")&&Boolean(document.querySelector(".doc-no"))'))
  let sales=(await invoke('listSales',{from:calendar,to:calendar})).data
  const saleId=sales.find(x=>x.comment==='UI created').id
  const dateCell=await js('document.querySelector(".table-panel tbody tr td:nth-child(2)").innerText')
  assert.match(dateCell,/^\d{2}\.\d{2}\.\d{4}$/)
  await run(`document.querySelector('button[aria-label="Изменить: Комментарий"]').click()`)
  await waitFor(()=>js('Boolean(document.querySelector(".quick-editor input"))'))
  await fill('.quick-editor input','UI inline saved')
  await run(`document.querySelector('.quick-editor button[type=submit]').click()`)
  await waitFor(()=>js('document.body.innerText.includes("UI inline saved")&&!document.querySelector(".quick-editor")'))
  assert.equal((await invoke('getSale',{saleId})).data.comment,'UI inline saved')
  await run(`document.querySelector('button[aria-label="Изменить: Дата продажи"]').click()`)
  await waitFor(()=>js('Boolean(document.querySelector(".quick-editor input[type=date]"))'))
  const otherDay=calendar.slice(0,8)+String(day.getDate()===1?2:day.getDate()-1).padStart(2,'0')
  await fill('.quick-editor input',otherDay)
  await run(`document.querySelector('.quick-editor button[type=submit]').click()`)
  await waitFor(()=>js('!document.querySelector(".quick-editor")'))
  assert.equal((await invoke('getSale',{saleId})).data.soldAt,otherDay)
  await click('Изменить состав')
  await waitFor(()=>js('document.querySelector(".modal h2")?.innerText==="Редактирование продажи"'))
  await fillLabel('Дата продажи',calendar)
  await fill('.cart-row .qty-control input','2')
  await fill('.cart-row .money-input input','7.01')
  await click('Сохранить изменения')
  await waitFor(()=>js('!document.querySelector(".modal")&&document.querySelector(".table-panel tbody tr td:nth-child(5)")?.innerText==="2 шт."'))
  let sale=(await invoke('getSale',{saleId})).data
  assert.equal(sale.items[0].quantity,2);assert.equal(sale.items[0].salePrice,701);assert.equal(sale.soldAt,calendar)
  assert.equal((await invoke('listProducts',{search:'UI модель'})).data.find(x=>x.size==='48').quantity,5)
  await click('Изменить состав')
  await waitFor(()=>js('Boolean(document.querySelector(".cart-row"))'))
  await click('Заменить товар')
  await waitFor(()=>js('Boolean(document.querySelector(".picker-list button"))'))
  await run(`Array.from(document.querySelectorAll('.picker-list button')).find(x=>x.innerText.includes('UI другая')).click()`)
  await waitFor(()=>js('document.querySelectorAll(".modal").length===1&&document.querySelector(".cart-row").innerText.includes("UI другая")'))
  await click('Сохранить изменения')
  await waitFor(()=>js('!document.querySelector(".modal")'))
  assert.equal((await invoke('getSale',{saleId})).data.items[0].article,otherArticle)
  assert.equal((await invoke('listProducts',{search:'UI модель'})).data.find(x=>x.size==='48').quantity,7)
  assert.equal((await invoke('listProducts',{search:'UI другая'})).data[0].quantity,0)
  await click('Изменить состав')
  await waitFor(()=>js('Boolean(document.querySelector(".cart-row"))'))
  await click('Заменить товар')
  await waitFor(()=>js('Boolean(document.querySelector(".picker-list button"))'))
  await run(`Array.from(document.querySelectorAll('.picker-list button')).find(x=>x.innerText.includes('UI модель')&&x.innerText.includes('48')).click()`)
  await waitFor(()=>js('document.querySelectorAll(".modal").length===1&&document.querySelector(".cart-row").innerText.includes("UI модель")'))
  await fill('.cart-row .money-input input','7.01')
  await click('Сохранить изменения')
  await waitFor(()=>js('!document.querySelector(".modal")'))
  sale=(await invoke('getSale',{saleId})).data
  assert.equal(sale.items[0].article,products[0].article)
  assert.equal((await invoke('listProducts',{search:'UI другая'})).data[0].quantity,2)
  assert.equal((await invoke('listProducts',{search:'UI модель'})).data.find(x=>x.size==='48').quantity,5)
  await js('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))')
  fs.writeFileSync(path.join(shots,'sales.png'),(await win.webContents.capturePage()).toPNG())
  // Observe the actual export IPC to check the serialized date column.
  const {ipcMain}=require('electron')
  let exported
  ipcMain.removeHandler('boss-shop:export')
  ipcMain.handle('boss-shop:export',(_event,...args)=>{exported=args;return {ok:true}})
  await run(`const node=document.querySelector('.export-menu select');Object.getOwnPropertyDescriptor(HTMLSelectElement.prototype,'value').set.call(node,'csv');node.dispatchEvent(new Event('change',{bubbles:true}))`)
  await waitFor(()=>exported)
  assert.ok(JSON.stringify(exported).includes(dateCell))
  assert.ok(!JSON.stringify(exported).includes(calendar+'T'))
  // Error keeps the form and saved data intact; returned lines are visibly locked.
  const returned=await invoke('createReturn',{data:{saleId,date:calendar,items:[{saleItemId:sale.items[0].id,quantity:1}]}})
  assert.equal(returned.ok,true)
  await click('Изменить состав')
  await waitFor(()=>js('Boolean(document.querySelector(".cart-row small"))'))
  assert.equal(await js('document.querySelector(".cart-row .qty-control input").disabled'),true)
  assert.equal(await js('document.querySelector(".cart-row .money-input input").disabled'),true)
  await fillLabel('Комментарий','After partial return')
  await click('Сохранить изменения')
  await waitFor(()=>js('!document.querySelector(".modal")&&document.body.innerText.includes("After partial return")'))
  assert.equal((await invoke('getSale',{saleId})).data.items[0].returnedQuantity,1)
  await click('Изменить состав')
  await waitFor(()=>js('Boolean(document.querySelector(".modal .cart-row"))'))
  sale=(await invoke('getSale',{saleId})).data
  assert.equal((await invoke('updateSale',{sale:{id:saleId,date:calendar,paymentMethod:sale.paymentMethod,employeeId:sale.employeeId,comment:'External change',expectedVersion:sale.editVersion}})).ok,true)
  await fillLabel('Комментарий','Stale form must not overwrite')
  await click('Сохранить изменения')
  await waitFor(()=>js('Boolean(document.querySelector(".modal .notice.error"))'))
  assert.ok((await js('document.querySelector(".modal .notice.error").innerText')).includes('Откройте'))
  assert.equal((await invoke('getSale',{saleId})).data.comment,'External change')
  await click('Отмена',`document.querySelector('.modal')`)
  await require('./electron-catalog-ui.cjs')({js,run,click,fill,fillLabel,nav,invoke,waitFor,win,root,log,products,saleId,calendar,shots})
  log('features-ui',{saleId,models:2,variants:5,dateOnly:true,shots})
}
