const assert=require('node:assert/strict')
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto')
const asar=require('@electron/asar')
const root=path.resolve(__dirname,'..'),pkg=require('../package.json'),lock=require('../package-lock.json')
assert.equal(pkg.version,lock.version);assert.equal(pkg.version,lock.packages[''].version)
const archive=path.join(root,'release','win-unpacked','resources','app.asar')
assert.equal(JSON.parse(asar.extractFile(archive,'package.json')).version,pkg.version)
const list=directory=>fs.readdirSync(path.join(root,directory),{withFileTypes:true}).flatMap(x=>x.isDirectory()?list(`${directory}/${x.name}`):[`${directory}/${x.name}`])
const files=[...list('electron'),...list('dist')]
for(const file of files)assert.deepEqual(asar.extractFile(archive,path.normalize(file)),fs.readFileSync(path.join(root,file)),`Packaged bytes differ: ${file}`)
const exe=fs.readFileSync(path.join(root,'release','win-unpacked','Boss Shop.exe'))
assert.equal(exe.readUInt16LE(exe.readUInt32LE(0x3c)+4),0x8664,'Packaged application must be x64')
const installer=path.join(root,'release',`BossShop-Setup-${pkg.version}-Win7-8-10-11-x64.exe`)
const bytes=fs.readFileSync(installer),sha256=crypto.createHash('sha256').update(bytes).digest('hex').toUpperCase()
const latest=fs.readFileSync(path.join(root,'release','latest.yml'),'utf8')
assert.ok(latest.includes(`version: ${pkg.version}`));assert.ok(latest.includes(path.basename(installer)))
assert.ok(latest.includes(crypto.createHash('sha512').update(bytes).digest('base64')),'Installer and latest.yml SHA512 mismatch')
const report={version:pkg.version,installer,bytes:bytes.length,sha256,archive,checkedFiles:files,architecture:'x64'}
fs.mkdirSync(path.join(root,'build',`verification-${pkg.version}`),{recursive:true})
fs.writeFileSync(path.join(root,'build',`verification-${pkg.version}`,'release.json'),JSON.stringify(report,null,2)+'\n')
console.log(JSON.stringify(report,null,2))
